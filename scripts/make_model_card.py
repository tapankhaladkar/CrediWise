"""Write docs/MODEL_CARD.md from reports/metrics.json.

Generated, not hand-written, so the card always matches the numbers the
model actually produced.

    python scripts/make_model_card.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from crediwise.explain import REASONS  # noqa: E402

METRICS = ROOT / "reports" / "metrics.json"
OUTPUT = ROOT / "docs" / "MODEL_CARD.md"


def pct(x: float, digits: int = 1) -> str:
    return f"{x * 100:.{digits}f}%"


def render(r: dict) -> str:
    d, sel, t, dec, pol = r["data"], r["selection"], r["test"], r["decisions"], r["policy"]
    out: list[str] = []
    add = out.append

    add("# Model card")
    add("")
    add(f"*Generated by `scripts/make_model_card.py` from `reports/metrics.json` "
        f"(trained {r['trained_at']}).*")
    add("")
    add("## What it does")
    add("")
    add("Predicts the probability that a credit card customer misses next month's "
        "payment, from the credit limit and the last six months of bills, payments "
        "and repayment status. A policy turns that probability into approve, refer "
        "or decline, and anything not approved comes with its reasons.")
    add("")
    add("**Suitable for:** demonstrating an end-to-end, evaluated and audited credit "
        "risk model on real data.")
    add("")
    add("**Not suitable for:** real lending decisions. The data is from one Taiwanese "
        "lender in 2005, the cost figures behind the decision policy are "
        "illustrative, and the model has not been validated on later or other data.")
    add("")
    add("## Data")
    add("")
    add(f"- UCI *Default of Credit Card Clients* (Yeh, 2009), CC BY 4.0 — see "
        f"[`DATA.md`](DATA.md)")
    add(f"- {d['rows']:,} customers, {d['duplicates_dropped']} duplicate records "
        f"dropped, leaving {d['customers']:,}")
    add(f"- {pct(d['default_rate'])} defaulted the following month")
    add(f"- Split {d['train']:,} train / {d['test']:,} test, stratified by outcome. "
        f"Every choice below was made on the training data; the test set was scored "
        f"once, at the end.")
    add("")
    add("## How the model was chosen")
    add("")
    add("Cross-validated AUC on the training data (5 folds):")
    add("")
    add("| Model | CV AUC |")
    add("|---|---|")
    add(f"| Logistic regression (benchmark) | {sel['logistic_regression_cv_auc']:.4f} ± "
        f"{sel['logistic_regression_cv_std']:.4f} |")
    add(f"| **Gradient boosting, tuned** | **{sel['gradient_boosting_cv_auc']:.4f} ± "
        f"{sel['gradient_boosting_cv_std']:.4f}** |")
    add("")
    add(f"Settings chosen by a randomised search over {sel['search_candidates']} "
        f"candidates; early stopping settled on {sel['trees_after_early_stopping']} trees.")
    add("")
    add("| Setting | Value |")
    add("|---|---|")
    for k, v in sel["best_params"].items():
        add(f"| `{k}` | {v} |")
    add("")
    add("## Results on the held-out test set")
    add("")
    add("| Measure | Model | Reference |")
    add("|---|---|---|")
    add(f"| AUC (ranking quality) | **{t['auc']:.4f}** | logistic regression "
        f"{t['logistic_regression_auc']:.4f}; coin flip 0.5 |")
    add(f"| KS statistic | {t['ks']:.4f} | |")
    add(f"| Precision-recall AUC | {t['pr_auc']:.4f} | random {t['default_rate']:.4f} |")
    add(f"| Brier score (lower is better) | {t['brier']:.4f} | no skill "
        f"{t['brier_baseline']:.4f} |")
    add(f"| Calibration error | {t['calibration_error']:.4f} | 0 = probabilities exact |")
    add("")
    add(f"The test AUC is {sel['gradient_boosting_cv_auc'] - t['auc']:.4f} below the "
        f"cross-validated estimate. A gap of this size is ordinary variation for a "
        f"single test set of {d['test']:,}; the test figure is the one to quote.")
    add("")
    add("Accuracy is deliberately not a headline: predicting \"will repay\" for "
        f"everyone is {pct(1 - t['default_rate'])} accurate and catches no defaulters.")
    add("")
    add("### Are the probabilities trustworthy?")
    add("")
    add("| Predicted range | Customers | Predicted default rate | Actual default rate |")
    add("|---|---|---|---|")
    for row in r["calibration"]:
        add(f"| {row['bin']} | {row['n']:,} | {pct(row['predicted'])} | "
            f"{pct(row['observed'])} |")
    add("")
    add("## Decisions")
    add("")
    add(f"- **Approve** when the probability of default is below "
        f"{pol['approve_below']:.3f}. Lending to a customer who defaults is set to cost "
        f"{pol['cost_default']:g}x as much as turning away one who would have repaid, "
        f"and this is where the two balance.")
    add(f"- **Decline** at {pol['decline_at']:.2f} or above: more likely than not to "
        f"default.")
    add("- **Refer** to a person in between.")
    add("")
    add("On the test set:")
    add("")
    add("| | |")
    add("|---|---|")
    add(f"| Approved / referred / declined | {pct(dec['approved_share'])} / "
        f"{pct(dec['referred_share'])} / {pct(dec['declined_share'])} |")
    add(f"| Default rate among approved | **{pct(dec['default_rate_among_approved'])}**, "
        f"against {pct(dec['default_rate_if_all_approved'])} if everyone were approved |")
    add(f"| Defaulters kept from automatic approval | {pct(dec['defaulters_not_approved'])} "
        f"({pct(dec['defaulters_declined'])} declined outright) |")
    add(f"| Customers who repaid but were declined | {pct(dec['payers_declined'])} |")
    add("")
    add("The cost ratio is illustrative; a lender would set it from its own losses "
        "and margins, and the thresholds follow.")
    add("")
    add("## What drives the predictions")
    add("")
    add("Average size of each feature's contribution (SHAP) on the test set:")
    add("")
    add("| Feature | Meaning | Mean \\|SHAP\\| |")
    add("|---|---|---|")
    for row in r["importance"][:10]:
        add(f"| `{row['feature']}` | {REASONS[row['feature']]} | "
            f"{row['mean_abs_shap']:.3f} |")
    add("")
    add("## Fairness")
    add("")
    scope = r["fairness"]["_scope"]
    add(f"The model never sees sex, marital status, age or education. The audit "
        f"checks outcomes for each anyway. It can test "
        f"{', '.join(scope['testable'])}; it cannot test "
        f"{', '.join(scope['not_in_data'])}, which are not in the data. Full "
        f"explanation in [`FAIRNESS.md`](FAIRNESS.md).")
    add("")
    add("| Group | Approval ratio | Four-fifths rule | Repayment ratio | Amplification "
        "| Equal-opportunity gap |")
    add("|---|---|---|---|---|---|")
    labels = {"sex": "Sex", "marital_status": "Marital status", "age_band": "Age band",
              "education": "Education"}
    for dim, label in labels.items():
        s = r["fairness"][dim]["summary"]
        add(f"| {label} | {s['approval_ratio']:.3f} | "
            f"{'pass' if s['passes_four_fifths'] else '**fail**'} | "
            f"{s['repayment_ratio']:.3f} | {s['amplification']:.2f} | "
            f"{s['equal_opportunity_gap']:.3f} |")
    add("")
    add("Amplification below 1 means approvals are more unequal than actual "
        "repayment; above 1, less.")
    add("")
    for dim, label in labels.items():
        res = r["fairness"][dim]
        add(f"### {label}")
        add("")
        add("| Group | Customers | Actual default | Predicted default | Approved "
            "| Approved, if repaid |")
        add("|---|---|---|---|---|---|")
        for g in res["by_group"]:
            add(f"| {g['group']} | {g['n']:,} | {pct(g['default_rate'])} | "
                f"{pct(g['predicted_default_rate'])} | {pct(g['approval_rate'])} | "
                f"{pct(g['approval_rate_if_repaid'])} |")
        if res["too_small_to_assess"]:
            small = ", ".join(f"{k} ({v})" for k, v in res["too_small_to_assess"].items())
            add("")
            add(f"Too few customers in the test set to assess: {small}.")
        add("")
    add("## Limitations")
    add("")
    add("- **One lender, one place, one year.** 2005 Taiwan. Nothing here shows the "
        "model would hold up elsewhere or later.")
    add("- **No test across time.** All customers come from the same six months, so "
        "the evaluation cannot measure drift.")
    add("- **Two of the repayment codes are undocumented.** -2 and 0 are the most "
        "common values but are not defined by the source; they are used as ordered "
        "codes without inventing a meaning.")
    add("- **The fairness audit is bounded by the data.** Four protected bases are "
        "absent, and some groups are too small to assess.")
    add("- **The decision policy's costs are illustrative.**")
    return "\n".join(out) + "\n"


def main() -> None:
    if not METRICS.exists():
        sys.exit(f"{METRICS} not found; run `make train` first.")
    OUTPUT.write_text(render(json.loads(METRICS.read_text())))
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
